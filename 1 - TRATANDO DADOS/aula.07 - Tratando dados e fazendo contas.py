#VAMOS FAZER DIVISÃO 

val1 = int(input ('DIGITE UM VALOR: '))
val2 = int(input('DIGITE UM SEGUNDO VALOR: '))
val3 = int(input('DIGITE UM TERCEIRO VALOR: '))

soma = (val1 + val2 + val3)
div = int(input('AGORA ESCREVA UM NUMERO AO QUAL VOCÊ QUEIRA DIVIDIR: '))
r = (soma / div)

print('O resultado da soma de {}, {}, e {}, dividido por {} é igual a {}'. format(val1,val2,val3,div,r))


