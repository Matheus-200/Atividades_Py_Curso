#SOMA E MULTIPLICAÇÃO
print('VAMOS FAZER A SOMA DE UM VALOR E MULTIPLICA-LO POR OUTRO NÚMERO')
rs1 = int(input('Digite o primeiro valor: '))
rs2 = int(input('Digite o segundo valor: '))
rs3 = int(input('Digite o terceiro valor: '))

soma = (rs1 + rs2 + rs3 )

divisao = int(input('Agora escreva o número pelo qual você quer dividir: ' ))
result = (soma / divisao)

print('O resultado da soma dividido por {} é igual a: {:.1f}'.format(soma, result))

